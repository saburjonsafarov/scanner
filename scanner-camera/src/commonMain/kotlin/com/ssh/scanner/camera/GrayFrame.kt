package com.ssh.scanner.camera

import com.ssh.scanner.image.GrayImage

/**
 * Кадр камеры вместе с тем, что нужно знать о его ориентации.
 *
 * Пиксели и ориентация разделены сознательно: детектору ориентация безразлична — он найдёт код под
 * любым углом, — а вот интерфейсу она нужна, чтобы положить рамку туда, где пользователь видит код.
 */
public data class GrayFrame(
    val image: GrayImage,
    /** На сколько градусов повернуть кадр, чтобы он совпал с ориентацией экрана. */
    val rotationDegrees: Int,
    /** Фронтальная камера отдаёт зеркальное изображение. */
    val mirrored: Boolean,
)
